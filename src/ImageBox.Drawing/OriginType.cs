namespace ImageBox.Drawing;

/// <summary>
/// Dictates where the origin of an object is
/// </summary>
public enum OriginType
{
    /// <summary>
    /// Top left corner
    /// </summary>
    TopLeft = 0,
    /// <summary>
    /// Top center
    /// </summary>
    TopCenter = 1,
    /// <summary>
    /// Top right corner
    /// </summary>
    TopRight = 2,
    /// <summary>
    /// Center left
    /// </summary>
    CenterLeft = 3,
    /// <summary>
    /// Center
    /// </summary>
    Center = 4,
    /// <summary>
    /// Center right
    /// </summary>
    CenterRight = 5,
    /// <summary>
    /// Bottom left corner
    /// </summary>
    BottomLeft = 6,
    /// <summary>
    /// Bottom center
    /// </summary>
    BottomCenter = 7,
    /// <summary>
    /// Bottom right corner
    /// </summary>
    BottomRight = 8
}
